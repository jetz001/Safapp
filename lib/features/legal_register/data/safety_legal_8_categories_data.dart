  /// Find a master item by its unique ITEM-ID
  static LegalMasterItemModel? findByItemId(String itemId) {
    try {
      return masterItems.firstWhere((e) => e.itemId.toUpperCase() == itemId.toUpperCase());
    } catch (_) {
      return null;
    }
  }

  /// Filter master items by category
  static List<LegalMasterItemModel> findByCategory(String category) {
    if (category.isEmpty || category.toUpperCase() == 'ALL') {
      return List.unmodifiable(masterItems);
    }
    return masterItems
        .where((e) => e.category.toUpperCase() == category.toUpperCase())
        .toList();
  }

  /// Search across master items by keyword
  static List<LegalMasterItemModel> search(String query, {String? category}) {
    var list = masterItems;
    if (category != null && category.isNotEmpty && category.toUpperCase() != 'ALL') {
      list = list.where((e) => e.category.toUpperCase() == category.toUpperCase()).toList();
    }
    if (query.trim().isEmpty) return list;

    final q = query.trim().toLowerCase();
    return list.where((item) {
      return item.itemId.toLowerCase().contains(q) ||
          item.title.toLowerCase().contains(q) ||
          item.description.toLowerCase().contains(q) ||
          item.articleNo.toLowerCase().contains(q) ||
          item.lawNameTh.toLowerCase().contains(q) ||
          item.lawNameEn.toLowerCase().contains(q) ||
          item.complianceCriteria.toLowerCase().contains(q) ||
          item.applicabilityCriteria.toLowerCase().contains(q) ||
          item.penaltySummary.toLowerCase().contains(q) ||
          (item.officialFormName != null && item.officialFormName!.toLowerCase().contains(q));
    }).toList();
  }

  /// Generates initial assessment records for all 32 master items
  static List<LegalComplianceAssessmentModel> generateDefaultAssessments({
    String evaluatorName = 'จป.วิชาชีพ',

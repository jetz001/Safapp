  static final Map<String, ChemicalTlvItem> _casLookup = {
    for (final item in tlvList)
      if (item.casNumber != null && item.casNumber!.isNotEmpty)
        item.casNumber!.trim().toLowerCase(): item,
  };

  static final Map<int, ChemicalTlvItem> _seqLookup = {
    for (final item in tlvList) item.sequenceNo: item,
  };

  /// Looks up TLV item by exact CAS number (handles dash normalization).
  static ChemicalTlvItem? findByCas(String rawCas) {
    final query = rawCas.trim().toLowerCase();
    if (_casLookup.containsKey(query)) return _casLookup[query];

    // Clean match
    final clean = query.replaceAll(RegExp(r'[^a-zA-Z0-9]'), '');
    for (final entry in _casLookup.entries) {
      final entryClean = entry.key.replaceAll(RegExp(r'[^a-zA-Z0-9]'), '');
      if (entryClean == clean) return entry.value;
    }
    return null;
  }

  /// Looks up TLV item by sequence number (1-324).
  static ChemicalTlvItem? findBySequence(int seq) => _seqLookup[seq];

  /// Searches TLV items by Thai name, English name, or CAS number.
  static List<ChemicalTlvItem> search(String query, {int limit = 20}) {
    final q = query.trim().toLowerCase();
    if (q.isEmpty) return tlvList.take(limit).toList();

    final cleanQ = q.replaceAll(RegExp(r'[^a-zA-Z0-9\u0E00-\u0E7F]'), '');

    final results = <({ChemicalTlvItem item, int score})>[];

    for (final item in tlvList) {
      int score = 0;
      final cas = item.casNumber?.toLowerCase() ?? '';
      final cleanCas = cas.replaceAll(RegExp(r'[^a-zA-Z0-9]'), '');
      final en = item.englishName.toLowerCase();
      final th = item.thaiName.toLowerCase();

      if (cas == q || (cleanCas.isNotEmpty && cleanCas == cleanQ)) {
        score = 100;
      } else if (cas.startsWith(q) || (cleanCas.isNotEmpty && cleanCas.startsWith(cleanQ))) {
        score = 90;
      } else if (en == q || th == q) {
        score = 85;
      } else if (en.startsWith(q) || th.startsWith(q)) {
        score = 75;
      } else if (en.contains(q) || th.contains(q) || cas.contains(q)) {
        score = 50;
      }

      if (score > 0) {
        results.add((item: item, score: score));
      }
    }

    results.sort((a, b) => b.score.compareTo(a.score));
    return results.map((e) => e.item).take(limit).toList();
  }
